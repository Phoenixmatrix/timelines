// The README's list of retention categories (CORE-211), generated from the
// registry so it never drifts: every category with its scope, whether it is
// off until enabled, its defaults and bounds, and what it never deletes.
// docs.test.ts fails when README.md differs; regenerate it with
//   node apps/website/worker/retention/docs.ts

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { RetentionCategory, RetentionThreshold } from "../../shared/retention.ts";
import { CATEGORIES } from "./categories.ts";
import { cleanupFor } from "./cleanups/index.ts";

export const START = "<!-- retention-categories:start (generated by worker/retention/docs.ts) -->";
export const END = "<!-- retention-categories:end -->";

function threshold(t: RetentionThreshold): string {
  const unit = t.unit === "gib" ? " GiB" : "";
  return `${t.label}: ${t.default}${unit} (\`${t.key}\`, ${t.min}–${t.max}${unit})`;
}

function state(c: RetentionCategory): string {
  if (c.control === "active") return "always on (it ran before retention policies existed)";
  if (c.control === "fixed") return "always on, read-only";
  return cleanupFor(c.id)
    ? "off until enabled"
    : "off until enabled; no cleanup, so it never deletes anything";
}

/** One category as a Markdown list item, wrapped at 80 columns. */
function item(c: RetentionCategory): string {
  const text = [
    `**${c.label}** (\`${c.id}\`, ${c.scope === "site" ? "site" : "account"} scope; ${state(c)}).`,
    c.description,
    `${c.control === "policy" ? "Defaults when enabled" : "Defaults"}: ${c.thresholds.map(threshold).join("; ")}.`,
    `Never deletes: ${c.never.map((n) => n[0]!.toLowerCase() + n.slice(1)).join("; ")}.`,
    ...(c.overlaps?.length
      ? [
          `Can select the same records as ${c.overlaps.map((id) => `\`${id}\``).join(", ")}: a dry run of both counts them under each, a run removes each once.`,
        ]
      : []),
  ].join(" ");
  return wrap(`- ${text}`, "  ");
}

function wrap(text: string, indent: string): string {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(" ")) {
    if (line && line.length + 1 + word.length > 80) {
      lines.push(line);
      line = indent + word;
    } else line = line ? `${line} ${word}` : word;
  }
  lines.push(line);
  return lines.join("\n");
}

/** The generated section, markers included. */
export function categoriesMarkdown(): string {
  const scope = (s: "account" | "site", title: string) => [
    `**${title}**`,
    "",
    ...CATEGORIES.filter((c) => c.scope === s).map((c) => item(c)),
    "",
  ];
  return [
    START,
    "",
    ...scope("account", "Account scope"),
    ...scope("site", "Site scope"),
    END,
  ].join("\n");
}

/** README.md with the section replaced. */
export function withCategories(readme: string): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error("README.md has no retention categories markers");
  return readme.slice(0, start) + categoriesMarkdown() + readme.slice(end + END.length);
}

export const README = fileURLToPath(new URL("../../README.md", import.meta.url).href);

if (import.meta.main) writeFileSync(README, withCategories(readFileSync(README, "utf8")));
