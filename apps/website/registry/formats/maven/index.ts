/**
 * Maven 2 repository layout for mvn (wagon and the resolver transport),
 * Gradle, sbt and Leiningen. `maven-metadata.xml` is always generated by the
 * server; checksum sidecars are computed from stored digests, and uploaded
 * ones are verified against them.
 */

const SIDECAR_MAX_BYTES = 4096;
const POM_MAX_BYTES = 4 * 1024 * 1024;
const NO_CACHE = "private, max-age=0, must-revalidate";

type ChecksumSource = Pick<StoredBlob, "digest" | "md5" | "sha1" | "sha512">;

function checksumOf(blob: ChecksumSource, algo: ChecksumAlgo): string | null {
  return algo === "sha256" ? blob.digest.slice("sha256:".length) : blob[algo];
}

function hashText(text: string, algo: ChecksumAlgo): string {
  return createHash(algo).update(text).digest("hex");
}

function textResponse(
  c: AppContext,
  text: string,
  contentType: string,
  extra: Record<string, string> = {},
): Response {
  const bytes = new TextEncoder().encode(text);
  return new Response(c.req.method === "HEAD" ? null : bytes, {
    status: 200,
    headers: {
      "content-type": contentType,
      "content-length": String(bytes.length),
      "cache-control": NO_CACHE,
      ...extra,
    },
  });
}

async function readSmallBody(c: AppContext, limit: number): Promise<string> {
  const body = c.req.raw.body;
  if (!body) return "";
  const reader = body.getReader();
  const chunks: Uint8Array[] = [];
  let size = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    size += value.length;
    if (size > limit) {
      await reader.cancel();
      throw new RegistryError("too_large", `Body exceeds ${limit} bytes`);
    }
    chunks.push(value);
  }
  const out = new Uint8Array(size);
  let at = 0;
  for (const chunk of chunks) {
    out.set(chunk, at);
    at += chunk.length;
  }
  return new TextDecoder().decode(out);
}

