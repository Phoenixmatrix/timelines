async function ensureVersion(
  db: DB,
  packageId: string,
  version: string,
  publishedBy: string | null,
): Promise<VersionRow> {
  const existing = await getVersion(db, packageId, version);
  if (existing) return existing;
  try {
    return await createVersion(db, packageId, version, {}, publishedBy);
  } catch (error) {
    // A concurrent deploy of another file of this version created it first.
    const again = await getVersion(db, packageId, version);
    if (again) return again;
    throw error;
  }
}

async function deployChecksum(
  c: AppContext,
  repo: Repository,
  path: string,
  algo: ChecksumAlgo,
): Promise<Response> {
  const svc = services(c);
  const value = parseChecksum(await readSmallBody(c, SIDECAR_MAX_BYTES), algo);
  if (!value) throw RegistryError.badRequest(`Malformed ${algo} checksum for ${path}`);
  const file = await getFile<MavenFileMeta>(svc.db, repo.id, path);
  if (file && !isPending(file)) {
    const actual = checksumOf(file, algo);
    if (actual && actual !== value) {
      throw new RegistryError(
        "digest_invalid",
        `${algo} mismatch for ${path}: uploaded ${value}, stored artifact has ${actual}`,
      );
    }
    return c.body(null, 201);
  }
  // The artifact has not arrived yet: keep the checksum and verify it then.
  const blob = await storeBlob(svc.db, svc.bucket, value, { contentType: "text/plain" });
  await addFile(svc.db, {
    repoId: repo.id,
    path: `${path}.${algo}`,
    digest: blob.digest,
    size: blob.size,
    contentType: "text/plain",
    metadata: { pendingChecksum: algo } satisfies MavenFileMeta,
    createdBy: principalOf((await svc.access()).actor),
    overwrite: true,
  });
  return c.body(null, 201);
}

async function recordPom(
  svc: Services,
  blob: StoredBlob,
  coords: ArtifactCoordinates,
  packageName: string,
  repo: Repository,
  version: VersionRow,
): Promise<void> {
  if (blob.size > POM_MAX_BYTES) return;
  const pom = parsePom(await readBlobText(svc.bucket, blob.r2Key));
  await updateVersion(svc.db, version.id, {
    metadata: { ...version.metadata, packaging: pom.packaging, name: pom.name },
  });
  if (pom.packaging === "maven-plugin") {
    await ensurePackage(svc.db, repo.id, packageName, packageName, {
      pluginPrefix: pom.goalPrefix ?? pluginPrefix(coords.artifactId),
      ...(pom.name ? { pluginName: pom.name } : {}),
    } satisfies MavenPackageMeta);
  }
}

async function deployArtifact(
  c: AppContext,
  repo: Repository,
  path: string,
  coords: ArtifactCoordinates,
): Promise<Response> {
  const svc = services(c);
  const db = svc.db;
  const access = await svc.access();
  if (!c.req.raw.body) throw RegistryError.badRequest("Request body is empty");

  const expect: ExpectedDigests = {
    sha256: c.req.header("x-checksum-sha256") ?? undefined,
    sha1: c.req.header("x-checksum-sha1") ?? undefined,
    md5: c.req.header("x-checksum-md5") ?? undefined,
  };
  const pending = (await listFiles<MavenFileMeta>(db, repo.id, { prefix: `${path}.` })).filter(
    (f) => isPending(f) && CHECKSUM_ALGOS.some((algo) => f.path === `${path}.${algo}`),
  );
  for (const sidecar of pending) {
    const algo = sidecar.metadata.pendingChecksum as ChecksumAlgo;
    expect[algo] ??= (await readBlobText(svc.bucket, sidecar.r2Key)).trim();
  }
  const clearPending = async () => {
    for (const sidecar of pending) await deleteFile(db, repo.id, sidecar.path);
  };

  // SNAPSHOTs are mutable per build; releases only with immutable: false and delete rights.
  const existing = await getFile(db, repo.id, path);
  const overwrite =
    coords.snapshot ||
    (existing !== null && repo.config.immutable === false && (await access.can(repo, "delete")));

  const contentType = mavenContentType(path);
  let blob: StoredBlob;
  try {
    blob = await storeBlob(db, svc.bucket, c.req.raw.body, {
      contentType,
      maxBytes: repo.config.maxUploadBytes,
      expect,
    });
  } catch (error) {
    if (error instanceof RegistryError && error.code === "digest_invalid") await clearPending();
    throw error;
  }

  const name = `${coords.groupId}:${coords.artifactId}`;
  const pkg = await ensurePackage(db, repo.id, name, name, {
    groupId: coords.groupId,
    artifactId: coords.artifactId,
  } satisfies MavenPackageMeta);
  const actor = access.actor;
  const version = await ensureVersion(db, pkg.id, coords.baseVersion, principalOf(actor));
  await addFile(db, {
    repoId: repo.id,
    path,
    versionId: version.id,
    digest: blob.digest,
    size: blob.size,
    contentType,
    metadata: {
      classifier: coords.classifier,
      extension: coords.extension,
      timestamp: coords.timestamp,
      buildNumber: coords.buildNumber,
    } satisfies MavenFileMeta,
    createdBy: principalOf(actor),
    overwrite,
  });
  if (coords.extension === "pom" && !coords.classifier) {
    await recordPom(svc, blob, coords, name, repo, version);
  }
  await clearPending();
  await touchPackage(db, pkg.id);
  await audit(db, actor, "maven.deploy", {
    repoId: repo.id,
    target: path,
    detail: { digest: blob.digest, size: blob.size },
  });
  await svc.repoObject(repo).requestRebuild(repo.id);
  return c.body(null, 201);
}

async function deploy(c: AppContext): Promise<Response> {
  const svc = services(c);
  let repo = await loadRepo(c, "maven");
  if (repo.kind === "virtual") {
    const target = await deployTarget(svc, repo);
    if (!target) {
      throw new RegistryError("unsupported", `${repo.key} has no default deploy repository`);
    }
    repo = target;
  }
  if (repo.kind !== "local") throw new RegistryError("unsupported", "Deploy to a local repository");
  // Authorize before touching the body: Maven only sends credentials after a 401.
  await (await svc.access()).require(repo, "write");
  const path = safePath(restPath(c, 2));
  if (!path) throw RegistryError.badRequest("A file path is required");
  const { target, checksum } = parseMavenPath(path);

  if (target.kind === "metadata") {
    // Generated by the server; accept and drop what clients send. Drain rather
    // than cancel: Maven reuses the keep-alive connection, and an unread body
    // left on it stalls the next request (the metadata checksum PUT).
    await readSmallBody(c, 4 * 1024 * 1024);
    return c.body(null, 201);
  }
  if (target.kind !== "artifact") {
    throw RegistryError.badRequest(
      `${path} does not follow the Maven layout <group>/<artifact>/<version>/<artifact>-<version>[-<classifier>].<ext>`,
    );
  }
  if (checksum) return deployChecksum(c, repo, target.path, checksum);
  return deployArtifact(c, repo, path, target.coords);
}

async function remove(c: AppContext): Promise<Response> {
  const repo = await loadRepo(c, "maven");
  const svc = services(c);
  const access = await svc.access();
  await access.require(repo, "delete");
  if (repo.kind !== "local")
    throw new RegistryError("unsupported", "Delete from a local repository");
  const path = safePath(restPath(c, 2));
  if (!path) throw RegistryError.badRequest("Refusing to delete the repository root");
  const doomed = [
    ...((await getFile(svc.db, repo.id, path)) ? [path] : []),
    ...(await listFiles(svc.db, repo.id, { prefix: `${path}/` })).map((f) => f.path),
  ];
  if (doomed.length === 0) throw RegistryError.notFound(`${path} not found`);
  const touched = new Set<string>();
  for (const file of doomed) {
    const row: FileRow | null = await getFile(svc.db, repo.id, file);
    if (row?.versionId) touched.add(row.versionId);
    await deleteFile(svc.db, repo.id, file);
  }
  // Drop versions left without files, and mark their packages dirty.
  for (const versionId of touched) {
    const version = await svc.db
      .selectFrom("versions")
      .select(["id", "package_id"])
      .where("id", "=", versionId)
      .executeTakeFirst();
    if (!version) continue;
    const left = await svc.db
      .selectFrom("files")
      .select("id")
      .where("version_id", "=", versionId)
      .executeTakeFirst();
    if (!left) await svc.db.deleteFrom("versions").where("id", "=", versionId).execute();
    await touchPackage(svc.db, version.package_id);
  }
  await audit(svc.db, access.actor, "maven.delete", {
    repoId: repo.id,
    target: path,
    detail: { files: doomed.length },
  });
  await svc.repoObject(repo).requestRebuild(repo.id);
  return new Response(null, { status: 204 });
}

