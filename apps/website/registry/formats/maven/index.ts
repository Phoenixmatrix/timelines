async function readLocal(
  c: AppContext,
  repo: Repository,
  { target, checksum }: ParsedMavenPath,
): Promise<Response | null> {
  const svc = services(c);
  if (target.kind === "metadata") {
    const derived = await getDerived(svc.db, repo.id, target.path);
    if (!derived) return null;
    if (checksum) {
      const xml = await readDerivedText(svc.bucket, derived);
      return textResponse(c, hashText(xml, checksum), "text/plain");
    }
    return serveDerived(c.req.raw, svc.bucket, derived, {
      contentType: METADATA_CONTENT_TYPE,
      cacheControl: NO_CACHE,
    });
  }
  const file = await getFile<MavenFileMeta>(svc.db, repo.id, target.path);
  if (!file || isPending(file)) return null;
  if (checksum) {
    const value = checksumOf(file, checksum);
    return value ? textResponse(c, value, "text/plain") : null;
  }
  if (c.req.method === "GET") svc.waitUntil(countDownload(svc.db, file.id));
  return serveBlob(c.req.raw, svc.bucket, file, {
    contentType: file.contentType,
    headers: {
      "x-checksum-sha256": file.digest.slice(7),
      ...(file.sha1 ? { "x-checksum-sha1": file.sha1 } : {}),
      ...(file.md5 ? { "x-checksum-md5": file.md5 } : {}),
    },
  });
}

/** A cached remote entry's raw bytes (binary-safe), refreshed with a TTL. */
async function remoteMutable(
  c: AppContext,
  repo: Repository,
  path: string,
  contentType: string,
): Promise<Response | null> {
  const svc = services(c);
  const result = await cachedMetadata(svc, repo, path);
  if (result.status !== 200) return null;
  const derived = await getDerived(svc.db, repo.id, `upstream/${path}`);
  if (!derived) return textResponse(c, result.text, contentType);
  return serveDerived(c.req.raw, svc.bucket, derived, { contentType, cacheControl: NO_CACHE });
}

async function remoteArtifactCached(svc: Services, repo: Repository, path: string) {
  const entry = await svc.db
    .selectFrom("remote_entries")
    .select(["status", "digest"])
    .where("repo_id", "=", repo.id)
    .where("path", "=", `artifact/${path}`)
    .executeTakeFirst();
  return entry?.status === 200 ? entry : null;
}

async function remoteArtifact(
  c: AppContext,
  repo: Repository,
  path: string,
): Promise<{ blob: StoredBlob; contentType: string } | null> {
  const svc = services(c);
  let expect: ExpectedDigests | undefined;
  if (!(await remoteArtifactCached(svc, repo, path))) {
    const sidecar = await cachedMetadata(svc, repo, `${path}.sha1`);
    const sha1 = sidecar.status === 200 ? parseChecksum(sidecar.text, "sha1") : null;
    if (sha1) expect = { sha1 };
  }
  try {
    return await cachedArtifact(svc, repo, path, {
      expect,
      contentType: mavenContentType(path),
    });
  } catch (error) {
    if (error instanceof RegistryError && error.code === "digest_invalid") {
      throw new RegistryError(
        "upstream_error",
        `Upstream ${path} does not match its .sha1: ${error.message}`,
      );
    }
    throw error;
  }
}

async function readRemote(
  c: AppContext,
  repo: Repository,
  { target, checksum }: ParsedMavenPath,
): Promise<Response | null> {
  const svc = services(c);
  const coords = target.kind === "artifact" ? target.coords : null;
  // Timestamped SNAPSHOT builds and releases never change: fetch once.
  const immutable = coords !== null && (!coords.snapshot || coords.timestamp !== null);
  if (!immutable) {
    const path = checksum ? `${target.path}.${checksum}` : target.path;
    return remoteMutable(
      c,
      repo,
      path,
      checksum
        ? "text/plain"
        : target.kind === "metadata"
          ? METADATA_CONTENT_TYPE
          : mavenContentType(path),
    );
  }
  if (checksum) {
    const cached = await remoteArtifactCached(svc, repo, target.path);
    const blob = cached?.digest
      ? await svc.db
          .selectFrom("blobs")
          .select(["digest", "md5", "sha1", "sha512"])
          .where("digest", "=", cached.digest)
          .executeTakeFirst()
      : undefined;
    const value = blob ? checksumOf(blob, checksum) : null;
    if (value) return textResponse(c, value, "text/plain");
    return remoteMutable(c, repo, `${target.path}.${checksum}`, "text/plain");
  }
  const found = await remoteArtifact(c, repo, target.path);
  if (!found) return null;
  return serveBlob(c.req.raw, svc.bucket, found.blob, {
    contentType: found.contentType,
    headers: found.blob.sha1 ? { "x-checksum-sha1": found.blob.sha1 } : {},
  });
}

/**
 * Members that may serve `groupId`, locals first. Pinned namespaces match the
 * dotted groupId (`com.acme.*` also covers `com.acme`) or the path form
 * (`com/acme/**`); pinned groups never reach remote members.
 */
async function mavenCandidates(
  svc: Services,
  repo: Repository,
  groupId: string,
  artifactId: string | null,
): Promise<Repository[]> {
  const list = await candidates(svc, repo, groupId);
  const path = groupPath(groupId);
  const forms = [groupId, `${groupId}.`, path, `${path}/`];
  if (artifactId) forms.push(`${groupId}:${artifactId}`, `${path}/${artifactId}`);
  if (!forms.some((name) => isPinned(repo, name))) return list;
  return list.filter((member) => member.kind === "local");
}

async function memberMetadata(
  c: AppContext,
  member: Repository,
  path: string,
): Promise<MavenMetadata | null> {
  const svc = services(c);
  if (member.kind === "local") {
    const derived = await getDerived(svc.db, member.id, path);
    return derived ? parseMetadataXml(await readDerivedText(svc.bucket, derived)) : null;
  }
  const result = await cachedMetadata(svc, member, path);
  return result.status === 200 ? parseMetadataXml(result.text) : null;
}

async function readMember(
  c: AppContext,
  member: Repository,
  parsed: ParsedMavenPath,
): Promise<Response | null> {
  return member.kind === "remote" ? readRemote(c, member, parsed) : readLocal(c, member, parsed);
}

async function readVirtual(
  c: AppContext,
  repo: Repository,
  parsed: ParsedMavenPath,
): Promise<Response | null> {
  const svc = services(c);
  const { target, checksum } = parsed;
  const firstOf = async (members: Repository[]) => {
    for (const member of members) {
      const response = await readMember(c, member, parsed);
      if (response) return response;
    }
    return null;
  };

  if (target.kind === "artifact") {
    const { groupId, artifactId } = target.coords;
    return firstOf(await mavenCandidates(svc, repo, groupId, artifactId));
  }
  const segments = target.path.split("/").slice(0, -1);
  if (target.kind !== "metadata") {
    return firstOf(await mavenCandidates(svc, repo, segments.join("."), null));
  }
  const last = segments[segments.length - 1]!;
  if (isSnapshot(last) && segments.length >= 3) {
    const group = segments.slice(0, -2).join(".");
    return firstOf(await mavenCandidates(svc, repo, group, segments[segments.length - 2]!));
  }

  // Artifact-level versions and group-level plugins, unioned across members.
  const artifactGroup = segments.slice(0, -1).join(".");
  const forArtifact = artifactGroup ? await mavenCandidates(svc, repo, artifactGroup, last) : [];
  const forGroup = await mavenCandidates(svc, repo, segments.join("."), null);
  const docs = new Map<string, MavenMetadata | null>();
  const load = async (member: Repository) => {
    if (!docs.has(member.id)) docs.set(member.id, await memberMetadata(c, member, target.path));
    return docs.get(member.id) ?? null;
  };
  const parts: MavenMetadata[] = [];
  for (const member of forArtifact) {
    const doc = await load(member);
    if (doc?.versioning) {
      parts.push({ groupId: doc.groupId, artifactId: doc.artifactId, versioning: doc.versioning });
    }
  }
  for (const member of forGroup) {
    const doc = await load(member);
    if (doc?.plugins?.length) parts.push({ plugins: doc.plugins });
  }
  const merged = mergeMetadata(parts);
  if (!merged) return null;
  const xml = writeMetadataXml(merged);
  return checksum
    ? textResponse(c, hashText(xml, checksum), "text/plain")
    : textResponse(c, xml, METADATA_CONTENT_TYPE);
}

