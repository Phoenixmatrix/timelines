function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (ch) => `&#${ch.charCodeAt(0)};`);
}

async function listing(
  svc: Services,
  repo: Repository,
  dir: string,
): Promise<{ name: string; folder: boolean; size?: number }[] | null> {
  const prefix = dir ? `${dir}/` : "";
  const files = (await listFiles<MavenFileMeta>(svc.db, repo.id, { prefix, limit: 10_000 })).filter(
    (f) => !isPending(f),
  );
  const metadata = (await listDerived(svc.db, repo.id, prefix)).filter((d) =>
    d.path.endsWith(`/${METADATA_FILE}`),
  );
  const entries = [
    ...files.map((f) => ({ path: f.path, size: f.size })),
    ...metadata.map((d) => ({ path: d.path, size: d.size })),
  ];
  if (entries.length === 0 && dir) return null;
  const folders = new Set<string>();
  const children = new Map<string, number>();
  for (const entry of entries) {
    const rest = entry.path.slice(prefix.length);
    const slash = rest.indexOf("/");
    if (slash === -1) children.set(rest, entry.size);
    else folders.add(rest.slice(0, slash));
  }
  return [
    ...[...folders].sort().map((name) => ({ name, folder: true })),
    ...[...children.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, size]) => ({ name, folder: false, size })),
  ];
}

function listingHtml(title: string, children: { name: string; folder: boolean; size?: number }[]) {
  const rows = children
    .map((child) => {
      const href = encodeURIComponent(child.name) + (child.folder ? "/" : "");
      const label = escapeHtml(child.name + (child.folder ? "/" : ""));
      const size = child.folder ? "-" : String(child.size);
      return `<a href="${href}">${label}</a>${" ".repeat(Math.max(1, 60 - label.length))}${size}`;
    })
    .join("\n");
  const safeTitle = escapeHtml(title);
  return new Response(
    `<!doctype html><html><head><meta charset="utf-8"><title>${safeTitle}</title></head><body><h1>${safeTitle}</h1><pre><a href="../">../</a>\n${rows}</pre></body></html>`,
    { headers: { "content-type": "text/html; charset=utf-8", "cache-control": NO_CACHE } },
  );
}

async function read(c: AppContext): Promise<Response> {
  const repo = await loadRepo(c, "maven");
  const svc = services(c);
  await (await svc.access()).require(repo, "read");
  const raw = restPath(c, 2);
  const path = safePath(raw);

  if (path && !raw.endsWith("/")) {
    const parsed = parseMavenPath(path);
    const found =
      repo.kind === "local"
        ? await readLocal(c, repo, parsed)
        : repo.kind === "remote"
          ? await readRemote(c, repo, parsed)
          : await readVirtual(c, repo, parsed);
    if (found) return found;
  }
  if (repo.kind === "local") {
    const children = await listing(svc, repo, path);
    if (children) {
      if (path && !raw.endsWith("/")) {
        return c.redirect(`${new URL(c.req.url).pathname}/`, 301);
      }
      return listingHtml(`${repo.key}/${path}`, children);
    }
  }
  throw RegistryError.notFound(`${path || "/"} not found`);
}

