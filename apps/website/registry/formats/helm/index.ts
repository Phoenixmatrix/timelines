async function readableMembers(svc: Services, repo: Repository) {
  const access = await svc.access();
  const list = [];
  for (const member of await members(svc, repo)) {
    if (await access.can(member.repo, "read")) list.push(member);
  }
  return [
    ...list.filter((m) => m.repo.kind === "local"),
    ...list.filter((m) => m.repo.kind === "remote"),
  ];
}

async function virtualIndex(svc: Services, repo: Repository): Promise<string> {
  const sources: {
    member: Awaited<ReturnType<typeof readableMembers>>[number];
    file: DerivedFile;
  }[] = [];
  for (const member of await readableMembers(svc, repo)) {
    if (member.repo.kind === "local") {
      const file = await getDerived(svc.db, member.repo.id, INDEX);
      if (file) sources.push({ member, file });
    } else {
      // An unreachable upstream with nothing cached must not break the whole index.
      const remote = await remoteIndex(svc, member.repo).catch(() => null);
      if (remote) sources.push({ member, file: remote.index });
    }
  }
  const key = sha256(
    JSON.stringify({
      updated: repo.updatedAt,
      config: [repo.config.pinnedNamespaces, repo.config.mergeVersions],
      sources: sources.map((s) => [
        s.member.repo.id,
        s.file.sha256,
        s.member.include,
        s.member.exclude,
      ]),
    }),
  );
  const memoPath = `merged/${key}/${INDEX}`;
  const hit = await getDerived(svc.db, repo.id, memoPath);
  if (hit) return readDerivedText(svc.bucket, hit);

  const target = `${repoUrl(svc, repo.key)}/`;
  const indexes: HelmIndex[] = [];
  for (const { member, file } of sources) {
    const index = parseIndex(await readDerivedText(svc.bucket, file));
    const own = `${repoUrl(svc, member.repo.key)}/`;
    const entries: HelmIndex["entries"] = {};
    for (const [name, versions] of Object.entries(index.entries)) {
      if (!memberAllows(member, name)) continue;
      if (member.repo.kind === "remote" && isPinned(repo, name)) continue;
      entries[name] = versions.map((v) => ({
        ...v,
        urls: v.urls.map((u) => (u.startsWith(own) ? target + u.slice(own.length) : u)),
      }));
    }
    indexes.push({ ...index, entries });
  }
  const text = serializeIndex(
    mergeIndexes(indexes, { mergeVersions: repo.config.mergeVersions === true }),
  );
  await putDerived(svc.db, svc.bucket, repo.id, memoPath, text, INDEX_TYPE);
  for (const stale of await listDerived(svc.db, repo.id, "merged/")) {
    if (stale.path !== memoPath) await deleteDerived(svc.db, repo.id, stale.path);
  }
  return text;
}

/** The index text any kind of repository serves, or null. */
async function indexText(svc: Services, repo: Repository): Promise<string | null> {
  if (repo.kind === "virtual") return virtualIndex(svc, repo);
  if (repo.kind === "remote") {
    const remote = await remoteIndex(svc, repo);
    return remote ? readDerivedText(svc.bucket, remote.index) : null;
  }
  const file = await getDerived(svc.db, repo.id, INDEX);
  return file ? readDerivedText(svc.bucket, file) : emptyIndex();
}

