async function localCharts(svc: Services, repo: Repository): Promise<ChartVersion[]> {
  const rows = await svc.db
    .selectFrom("versions as v")
    .innerJoin("packages as p", "p.id", "v.package_id")
    .select(["v.metadata", "v.status"])
    .where("p.repo_id", "=", repo.id)
    .execute();
  const base = repoUrl(svc, repo.key);
  const charts: ChartVersion[] = [];
  for (const row of rows) {
    if (row.status === "yanked") continue;
    const meta = JSON.parse(row.metadata) as HelmVersionMeta;
    if (!meta.chart) continue;
    charts.push({
      ...meta.chart,
      urls: [`${base}/charts/${chartFilename(meta.chart.name, meta.chart.version)}`],
      created: meta.created,
      digest: meta.digest,
    });
  }
  return charts;
}

async function rebuildHelm(svc: Services, repo: Repository): Promise<void> {
  if (repo.kind !== "local") return;
  const charts = await localCharts(svc, repo);
  const generated = charts.reduce((max, c) => ((c.created ?? "") > max ? c.created! : max), "");
  const index = buildIndex(charts, generated || nowIso());
  await putDerived(svc.db, svc.bucket, repo.id, INDEX, serializeIndex(index), INDEX_TYPE);
}

function emptyIndex(): string {
  return serializeIndex({ apiVersion: "v1", entries: {}, generated: nowIso() });
}

