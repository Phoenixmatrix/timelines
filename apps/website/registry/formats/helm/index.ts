/**
 * Classic Helm chart repositories (`helm repo add`), with the ChartMuseum API
 * that `helm cm-push` speaks. index.yaml is generated by the RepoDO for local
 * repositories and computed (then memoized as a derived file) for remote and
 * virtual ones, whose chart URLs are rewritten to point back at this registry.
 */

const INDEX = "index.yaml";
const INDEX_TYPE = "application/x-yaml";
const CHART_TYPE = "application/gzip";
const DEFAULT_MAX_CHART_BYTES = 32 * 1024 * 1024;
/** Charts are parsed in memory, so the cap holds even if the repository allows more. */
const HARD_MAX_CHART_BYTES = 50 * 1024 * 1024;
const PROV_MAX_BYTES = 256 * 1024;
const NO_CACHE = "private, max-age=0, must-revalidate";

interface HelmVersionMeta {
  chart: ChartMetadata;
  /** sha256 hex of the .tgz */
  digest: string;
  created: string;
}

function sha256(text: string): string {
  return createHash("sha256").update(text).digest("hex");
}

function chartError(error: unknown): never {
  if (error instanceof ChartError) throw RegistryError.badRequest(error.message);
  throw error;
}

function repoUrl(svc: Services, key: string): string {
  return `${svc.baseUrl}/helm/${key}`;
}

function yamlResponse(c: AppContext, text: string): Response {
  const bytes = new TextEncoder().encode(text);
  return new Response(c.req.method === "HEAD" ? null : bytes, {
    headers: {
      "content-type": INDEX_TYPE,
      "content-length": String(bytes.length),
      "cache-control": NO_CACHE,
    },
  });
}

async function readBody(c: AppContext, limit: number): Promise<Uint8Array> {
  const declared = Number(c.req.header("content-length") ?? "0");
  if (declared > limit) throw new RegistryError("too_large", `Upload exceeds ${limit} bytes`);
  const reader = c.req.raw.body?.getReader();
  if (!reader) throw RegistryError.badRequest("Request body is empty");
  const chunks: Uint8Array[] = [];
  let size = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    size += value.length;
    if (size > limit) {
      await reader.cancel();
      throw new RegistryError("too_large", `Upload exceeds ${limit} bytes`);
    }
    chunks.push(value);
  }
  const out = new Uint8Array(size);
  let at = 0;
  for (const chunk of chunks) {
    out.set(chunk, at);
    at += chunk.length;
  }
  return out;
}

