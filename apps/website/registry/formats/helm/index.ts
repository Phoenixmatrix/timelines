function safeFilename(name: string): string | null {
  return /^[A-Za-z0-9][A-Za-z0-9._+-]*$/.test(name) && name.length <= 200 ? name : null;
}

/**
 * The upstream index with every chart URL pointing at
 * `/helm/<repo>/remote-charts/<digest>/<file>`, and the map from those paths
 * back to the upstream URLs. Only URLs in this map are ever fetched.
 */
async function remoteIndex(
  svc: Services,
  repo: Repository,
): Promise<{ index: DerivedFile; urls: string } | null> {
  const upstream = await cachedMetadata(svc, repo, INDEX);
  if (upstream.status !== 200) return null;
  const source = await getDerived(svc.db, repo.id, `upstream/${INDEX}`);
  const version = source?.sha256 ?? sha256(upstream.text);
  const indexPath = `rewritten/${version}/${INDEX}`;
  const urlsPath = `rewritten/${version}/urls.json`;
  const hit = await getDerived(svc.db, repo.id, indexPath);
  if (hit) return { index: hit, urls: urlsPath };

  let index: HelmIndex;
  try {
    index = parseIndex(upstream.text);
  } catch (error) {
    if (error instanceof ChartError) throw new RegistryError("upstream_error", error.message);
    throw error;
  }
  const indexUrl = upstreamUrl(repo, INDEX);
  const base = repoUrl(svc, repo.key);
  const urls: Record<string, string> = {};
  for (const versions of Object.values(index.entries)) {
    for (const version of versions) {
      version.urls = version.urls.flatMap((raw) => {
        let resolved: URL;
        try {
          resolved = new URL(String(raw), indexUrl);
        } catch {
          return [];
        }
        if (resolved.protocol !== "https:" && resolved.protocol !== "http:") return [String(raw)];
        const digest =
          typeof version.digest === "string" && /^[0-9a-f]{64}$/.test(version.digest)
            ? version.digest
            : null;
        const key = digest ?? `url-${sha256(resolved.href)}`;
        const file =
          safeFilename(decodeURIComponent(resolved.pathname.split("/").pop() ?? "")) ??
          safeFilename(chartFilename(version.name, version.version)) ??
          "chart.tgz";
        urls[`${key}/${file}`] = resolved.href;
        return [`${base}/remote-charts/${key}/${file}`];
      });
    }
  }
  await putDerived(svc.db, svc.bucket, repo.id, urlsPath, JSON.stringify(urls), "application/json");
  const out = await putDerived(
    svc.db,
    svc.bucket,
    repo.id,
    indexPath,
    serializeIndex(index),
    INDEX_TYPE,
  );
  for (const stale of await listDerived(svc.db, repo.id, "rewritten/")) {
    if (!stale.path.startsWith(`rewritten/${version}/`)) {
      await deleteDerived(svc.db, repo.id, stale.path);
    }
  }
  return { index: out, urls: urlsPath };
}

async function remoteChart(
  c: AppContext,
  repo: Repository,
  key: string,
  file: string,
): Promise<Response | null> {
  const svc = services(c);
  if (!safeFilename(file) || !/^(?:[0-9a-f]{64}|url-[0-9a-f]{64})$/.test(key)) return null;
  const digest = key.startsWith("url-") ? undefined : key;
  let found;
  try {
    found = await cachedArtifact(svc, repo, `remote-charts/${key}/${file}`, {
      contentType: file.endsWith(".tgz") ? CHART_TYPE : "application/octet-stream",
      expect: digest ? { sha256: digest } : undefined,
      fetcher: async () => {
        const current = await remoteIndex(svc, repo);
        const map = current ? await getDerived(svc.db, repo.id, current.urls) : null;
        const urls = map
          ? (JSON.parse(await readDerivedText(svc.bucket, map)) as Record<string, string>)
          : {};
        const target = urls[`${key}/${file}`];
        if (!target) return new Response(null, { status: 404 });
        return upstreamFetch(svc, repo, new URL(target), { timeoutMs: 10 * 60_000 });
      },
    });
  } catch (error) {
    if (error instanceof RegistryError && error.code === "digest_invalid") {
      throw new RegistryError("upstream_error", `Upstream chart does not match the index digest`);
    }
    throw error;
  }
  if (!found) return null;
  return serveBlob(c.req.raw, svc.bucket, found.blob, {
    contentType: found.contentType,
    filename: file,
  });
}

