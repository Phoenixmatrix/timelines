async function apiEntries(c: AppContext): Promise<HelmIndex["entries"]> {
  const repo = await readableRepo(c);
  const text = await indexText(services(c), repo);
  return text ? parseIndex(text).entries : {};
}

async function apiListCharts(c: AppContext): Promise<Response> {
  return c.json(await apiEntries(c));
}

async function apiGetChart(c: AppContext): Promise<Response> {
  const versions = (await apiEntries(c))[c.req.param("name") ?? ""];
  if (!versions) return c.json({ error: "chart not found" }, 404);
  return c.json(versions);
}

async function apiGetVersion(c: AppContext): Promise<Response> {
  const versions = (await apiEntries(c))[c.req.param("name") ?? ""] ?? [];
  const wanted = c.req.param("version");
  const found = wanted === "latest" ? versions[0] : versions.find((v) => v.version === wanted);
  if (!found) return c.json({ error: "chart version not found" }, 404);
  return c.json(found);
}

async function writableRepo(c: AppContext): Promise<Repository> {
  const svc = services(c);
  let repo = await loadRepo(c, "helm");
  if (repo.kind === "virtual") {
    const target = await deployTarget(svc, repo);
    if (!target) {
      throw new RegistryError("unsupported", `${repo.key} has no default deploy repository`);
    }
    repo = target;
  }
  if (repo.kind !== "local") throw new RegistryError("unsupported", "Upload to a local repository");
  await (await svc.access()).require(repo, "write");
  return repo;
}

function wantsForce(c: AppContext): boolean {
  const force = c.req.query("force");
  return force !== undefined && force !== "false" && force !== "0";
}

/** Existing content at `path`: identical bytes are fine; replacing needs ?force and delete. */
async function checkOverwrite(
  c: AppContext,
  repo: Repository,
  path: string,
  digest: string,
  force: boolean,
): Promise<"new" | "same" | "replace"> {
  const svc = services(c);
  const existing = await getFile(svc.db, repo.id, path);
  if (!existing) return "new";
  if (existing.digest === digest) return "same";
  if (!force || repo.config.immutable === true) {
    throw RegistryError.conflict(`${path.slice("charts/".length)} already exists`);
  }
  await (await svc.access()).require(repo, "delete");
  return "replace";
}

async function storeProv(
  c: AppContext,
  repo: Repository,
  bytes: Uint8Array,
  force: boolean,
  expectedFile?: string,
): Promise<string> {
  const svc = services(c);
  const chart = parseProvenance(new TextDecoder().decode(bytes));
  if (!chart) throw RegistryError.badRequest("Not a Helm provenance file");
  const file = `${chartFilename(chart.name, chart.version)}.prov`;
  if (expectedFile && expectedFile !== file) {
    throw RegistryError.badRequest(`Provenance is for ${file}, not ${expectedFile}`);
  }
  const blob = await storeBlob(svc.db, svc.bucket, bytes, { contentType: "text/plain" });
  const path = `charts/${file}`;
  const mode = await checkOverwrite(c, repo, path, blob.digest, force);
  if (mode === "same") return file;
  const pkg = await getPackage(svc.db, repo.id, chart.name);
  const version = pkg ? await getVersion(svc.db, pkg.id, chart.version) : null;
  await addFile(svc.db, {
    repoId: repo.id,
    path,
    versionId: version?.id ?? null,
    digest: blob.digest,
    size: blob.size,
    contentType: "text/plain",
    createdBy: principalOf((await svc.access()).actor),
    overwrite: mode === "replace",
  });
  return file;
}

async function storeChart(
  c: AppContext,
  repo: Repository,
  bytes: Uint8Array,
  force: boolean,
  expectedFile?: string,
): Promise<{ name: string; version: string }> {
  const svc = services(c);
  const access = await svc.access();
  let chart: ChartMetadata;
  try {
    chart = readChartArchive(bytes);
  } catch (error) {
    chartError(error);
  }
  const file = chartFilename(chart.name, chart.version);
  if (expectedFile && expectedFile !== file) {
    throw RegistryError.badRequest(`Chart.yaml says ${file}, not ${expectedFile}`);
  }
  const blob = await storeBlob(svc.db, svc.bucket, bytes, { contentType: CHART_TYPE });
  const path = `charts/${file}`;
  const mode = await checkOverwrite(c, repo, path, blob.digest, force);
  if (mode === "same") return chart;

  const pkg = await ensurePackage(svc.db, repo.id, chart.name, chart.name);
  const metadata: HelmVersionMeta = { chart, digest: blob.digest.slice(7), created: nowIso() };
  const existing = await getVersion(svc.db, pkg.id, chart.version);
  const version =
    existing ??
    (await createVersion(svc.db, pkg.id, chart.version, metadata, principalOf(access.actor)));
  if (existing) await updateVersion(svc.db, existing.id, { metadata });
  await addFile(svc.db, {
    repoId: repo.id,
    path,
    versionId: version.id,
    digest: blob.digest,
    size: blob.size,
    contentType: CHART_TYPE,
    createdBy: principalOf(access.actor),
    overwrite: mode === "replace",
  });
  await audit(svc.db, access.actor, "helm.publish", {
    repoId: repo.id,
    target: `${chart.name}@${chart.version}`,
    detail: { digest: blob.digest, size: blob.size, overwrite: mode === "replace" },
  });
  return chart;
}

function maxChartBytes(repo: Repository): number {
  return Math.min(repo.config.maxUploadBytes ?? DEFAULT_MAX_CHART_BYTES, HARD_MAX_CHART_BYTES);
}

async function apiUploadChart(c: AppContext): Promise<Response> {
  const repo = await writableRepo(c);
  const force = wantsForce(c);
  const body = await readBody(c, maxChartBytes(repo) + PROV_MAX_BYTES);
  const boundary = multipartBoundary(c.req.header("content-type"));
  let chart: Uint8Array | null = body;
  let prov: Uint8Array | null = null;
  if (boundary) {
    let parts;
    try {
      parts = parseMultipart(body, boundary);
    } catch (error) {
      chartError(error);
    }
    chart = parts.find((p) => p.name === "chart")?.data ?? null;
    prov = parts.find((p) => p.name === "prov")?.data ?? null;
    if (!chart && !prov) throw RegistryError.badRequest('Expected a "chart" or "prov" form field');
  }
  if (chart && chart.length > maxChartBytes(repo)) {
    throw new RegistryError("too_large", `Chart exceeds ${maxChartBytes(repo)} bytes`);
  }
  if (chart) await storeChart(c, repo, chart, force);
  if (prov) await storeProv(c, repo, prov, force);
  await services(c).repoObject(repo).requestRebuild(repo.id);
  return c.json({ saved: true }, 201);
}

async function apiUploadProv(c: AppContext): Promise<Response> {
  const repo = await writableRepo(c);
  const body = await readBody(c, PROV_MAX_BYTES + 4096);
  const boundary = multipartBoundary(c.req.header("content-type"));
  let prov = body;
  if (boundary) {
    const part = parseMultipart(body, boundary).find((p) => p.name === "prov");
    if (!part) throw RegistryError.badRequest('Expected a "prov" form field');
    prov = part.data;
  }
  await storeProv(c, repo, prov, wantsForce(c));
  return c.json({ saved: true }, 201);
}

async function putChart(c: AppContext): Promise<Response> {
  const repo = await writableRepo(c);
  const file = c.req.param("file") ?? "";
  if (file.endsWith(".tgz.prov")) {
    await storeProv(c, repo, await readBody(c, PROV_MAX_BYTES), wantsForce(c), file);
  } else if (file.endsWith(".tgz")) {
    await storeChart(c, repo, await readBody(c, maxChartBytes(repo)), wantsForce(c), file);
    await services(c).repoObject(repo).requestRebuild(repo.id);
  } else {
    throw RegistryError.badRequest("Upload <name>-<version>.tgz or its .prov");
  }
  return c.json({ saved: true }, 201);
}

async function apiDeleteVersion(c: AppContext): Promise<Response> {
  const svc = services(c);
  let repo = await loadRepo(c, "helm");
  if (repo.kind === "virtual") repo = (await deployTarget(svc, repo)) ?? repo;
  const access = await svc.access();
  await access.require(repo, "delete");
  if (repo.kind !== "local")
    throw new RegistryError("unsupported", "Delete from a local repository");
  const name = c.req.param("name") ?? "";
  const versionName = c.req.param("version") ?? "";
  const pkg = await getPackage(svc.db, repo.id, name);
  const version = pkg ? await getVersion(svc.db, pkg.id, versionName) : null;
  if (!pkg || !version) return c.json({ error: "chart version not found" }, 404);
  const file = chartFilename(name, versionName);
  for (const row of await listFiles(svc.db, repo.id, { versionIds: [version.id] })) {
    await deleteFile(svc.db, repo.id, row.path);
  }
  await deleteFile(svc.db, repo.id, `charts/${file}.prov`);
  await svc.db.deleteFrom("versions").where("id", "=", version.id).execute();
  if ((await listVersions(svc.db, pkg.id)).length === 0) await deletePackage(svc.db, pkg.id);
  await audit(svc.db, access.actor, "helm.delete", {
    repoId: repo.id,
    target: `${name}@${versionName}`,
  });
  await svc.repoObject(repo).requestRebuild(repo.id);
  return c.json({ deleted: true });
}

