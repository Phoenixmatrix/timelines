async function readableRepo(c: AppContext): Promise<Repository> {
  const repo = await loadRepo(c, "helm");
  await (await services(c).access()).require(repo, "read");
  return repo;
}

async function getIndex(c: AppContext): Promise<Response> {
  const repo = await readableRepo(c);
  const svc = services(c);
  if (repo.kind === "local") {
    const file = await getDerived(svc.db, repo.id, INDEX);
    if (!file) return yamlResponse(c, emptyIndex());
    return serveDerived(c.req.raw, svc.bucket, file, { cacheControl: NO_CACHE });
  }
  const text = await indexText(svc, repo);
  if (text === null) throw RegistryError.notFound("index.yaml not found upstream");
  return yamlResponse(c, text);
}

async function localChart(c: AppContext, repo: Repository, file: string): Promise<Response | null> {
  const svc = services(c);
  const row = await getFile(svc.db, repo.id, `charts/${file}`);
  if (!row) return null;
  if (c.req.method === "GET") svc.waitUntil(countDownload(svc.db, row.id));
  return serveBlob(c.req.raw, svc.bucket, row, { contentType: row.contentType, filename: file });
}

async function getChart(c: AppContext): Promise<Response> {
  const repo = await readableRepo(c);
  const svc = services(c);
  const file = c.req.param("file") ?? "";
  if (!safeFilename(file)) throw RegistryError.notFound("Chart not found");
  let found: Response | null = null;
  if (repo.kind === "local") found = await localChart(c, repo, file);
  else if (repo.kind === "virtual") {
    const name = parseChartFilename(file.replace(/\.prov$/, ""))?.name ?? file;
    found =
      (
        await firstMatch(svc, repo, name, (member) =>
          member.kind === "local" ? localChart(c, member, file) : Promise.resolve(null),
        )
      )?.value ?? null;
  }
  if (!found) throw RegistryError.notFound(`${file} not found`);
  return found;
}

async function getRemoteChart(c: AppContext): Promise<Response> {
  const repo = await readableRepo(c);
  const key = c.req.param("key") ?? "";
  const file = c.req.param("file") ?? "";
  let found: Response | null = null;
  if (repo.kind === "remote") found = await remoteChart(c, repo, key, file);
  else if (repo.kind === "virtual") {
    for (const member of await readableMembers(services(c), repo)) {
      if (member.repo.kind !== "remote") continue;
      found = await remoteChart(c, member.repo, key, file);
      if (found) break;
    }
  }
  if (!found) throw RegistryError.notFound(`${file} not found`);
  return found;
}

