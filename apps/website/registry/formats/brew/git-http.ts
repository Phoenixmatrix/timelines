import {
  advertiseV0,
  advertiseV2,
  concat,
  handleV0,
  handleV2,
  ObjectGraph,
  parseV2Request,
  type GitRefs,
} from "@gitmatrix/formats/git";

import { services, type AppContext } from "../../core/context.ts";
import { RegistryError } from "../../core/errors.ts";
import { loadRepo } from "../../core/http.ts";
import type { Repository } from "../../core/repos.ts";
import { BRANCH, mutateTap, tapName, type CommitResult } from "./tap.ts";
import { getHead, loadGraph, type Head } from "./store.ts";

/** Upload-pack requests are want/have lists; this is far beyond any real tap. */
const MAX_REQUEST_BYTES = 8 * 1024 * 1024;

const NO_CACHE = { "cache-control": "no-cache, max-age=0, must-revalidate", expires: "0" };

/** Reads a (possibly gzip-encoded) request body, refusing more than `max` bytes. */
export async function readBody(request: Request, max: number): Promise<Uint8Array> {
  if (!request.body) return new Uint8Array();
  let stream: ReadableStream<Uint8Array> = request.body;
  const encoding = request.headers.get("content-encoding")?.trim().toLowerCase();
  if (encoding === "gzip" || encoding === "x-gzip") {
    stream = stream.pipeThrough(
      new DecompressionStream("gzip") as unknown as ReadableWritablePair<Uint8Array, Uint8Array>,
    );
  } else if (encoding && encoding !== "identity") {
    throw RegistryError.badRequest(`Unsupported Content-Encoding ${encoding}`);
  }
  const chunks: Uint8Array[] = [];
  let size = 0;
  const reader = stream.getReader();
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      size += value.length;
      if (size > max) throw new RegistryError("too_large", `Request body exceeds ${max} bytes`);
      chunks.push(value);
    }
  } catch (error) {
    reader.cancel().catch(() => undefined);
    if (error instanceof RegistryError) throw error;
    throw RegistryError.badRequest("Malformed request body");
  }
  return concat(chunks);
}

/** Resolves `:repo` and checks the `homebrew-<tap>[.git]` segment. */
async function loadTap(c: AppContext): Promise<Repository> {
  const repo = await loadRepo(c, "brew");
  const segment = (c.req.param("tap") ?? "").replace(/\.git$/, "");
  if (segment !== `homebrew-${tapName(repo)}`) {
    throw RegistryError.notFound(
      `No such tap; clone ${services(c).baseUrl}/brew/${repo.key}/homebrew-${tapName(repo)}.git`,
    );
  }
  return repo;
}

/** HEAD, creating the tap's first commit on first use. */
export async function ensureHead(c: AppContext, repo: Repository): Promise<Head> {
  const svc = services(c);
  const head = await getHead(svc.db, repo.id);
  if (head) return head;
  const created = await mutateTap<CommitResult>(svc, repo, "refresh", {});
  return { oid: created.commit, seq: created.seq };
}

function refsOf(head: Head): GitRefs {
  return { headTarget: BRANCH, refs: [{ name: BRANCH, oid: head.oid }] };
}

function wantsV2(c: AppContext): boolean {
  return (c.req.header("git-protocol") ?? "")
    .split(":")
    .some((part) => part.trim() === "version=2");
}

function readOnly(c: AppContext, repo: Repository): Response {
  const api = `${services(c).baseUrl}/api/registry/brew/${repo.key}`;
  return new Response(
    [
      `This Homebrew tap is generated by gitmatrix and is read-only.`,
      `Publish formulae with: curl -T foo.rb -H "Authorization: Bearer $TOKEN" ${api}/Formula/foo.rb`,
      "",
    ].join("\n"),
    { status: 403, headers: { "content-type": "text/plain; charset=utf-8", ...NO_CACHE } },
  );
}

export async function infoRefs(c: AppContext): Promise<Response> {
  const repo = await loadTap(c);
  const service = c.req.query("service");
  if (service === "git-receive-pack") return readOnly(c, repo);
  if (service !== "git-upload-pack") {
    return new Response("This server only speaks git's smart HTTP protocol.\n", {
      status: 403,
      headers: { "content-type": "text/plain; charset=utf-8", ...NO_CACHE },
    });
  }
  await (await services(c).access()).require(repo, "read");
  const head = await ensureHead(c, repo);
  const body = wantsV2(c) ? advertiseV2() : advertiseV0(refsOf(head));
  return new Response(body, {
    headers: { "content-type": "application/x-git-upload-pack-advertisement", ...NO_CACHE },
  });
}

export async function uploadPack(c: AppContext): Promise<Response> {
  const repo = await loadTap(c);
  const svc = services(c);
  await (await svc.access()).require(repo, "read");
  const body = await readBody(c.req.raw, MAX_REQUEST_BYTES);
  const head = await ensureHead(c, repo);

  let command: string | null = null;
  try {
    command = parseV2Request(body).command;
  } catch {
    // Not a v2 command request, so protocol v0.
  }
  let chunks: Uint8Array[];
  if (command !== null || wantsV2(c)) {
    const graph =
      command === "fetch" ? await loadGraph(svc.db, repo.id, head.seq) : new ObjectGraph();
    chunks = handleV2(body, graph, refsOf(head));
  } else {
    chunks = handleV0(body, await loadGraph(svc.db, repo.id, head.seq));
  }
  return new Response(concat(chunks), {
    headers: { "content-type": "application/x-git-upload-pack-result", ...NO_CACHE },
  });
}

export async function receivePack(c: AppContext): Promise<Response> {
  return readOnly(c, await loadTap(c));
}
